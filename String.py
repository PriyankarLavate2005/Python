#String OPrations 
S1="Priyanka Lavate"
print(S1)
#counting the number of characters which are present inside S1
print(S1.count("P"))
#for capital case of String
print(S1.capitalize())
#for checking Index
print(S1.index("P"))
#Slicing Started
print(S1[:])
print(S1[-8:3])
#upper case
print(S1.upper())
#lower case
print(S1.lower())
#Strip for removing the Unwanted Space
print(S1.strip())
#When we want to replace paricular word that time we are using replace keyword
print(S1.replace("Priyanka","Pooja"))
